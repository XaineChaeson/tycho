test('a real node raw stream restores once, keeps the original receipt/task, and survives source deletion', async t => {
  const env = setup(t, final('历史正文（本次观察）'));
  const before = env.f.ledger.getTask(env.run.task_id);
  const report = await env.runner.recoverRunReport(env.run);
  assert.match(report.text, /历史正文/); assert.equal(report.source, 'recovered');
  assert.equal(report.complete, true);
  assert.deepEqual(env.f.ledger.getTask(env.run.task_id), before);
  assert.equal(env.f.ledger.getRun(env.run.id).receipt_json, env.run.receipt_json);
  assert.ok(env.reads.every(read => read.path.endsWith('/stdout.ndjson') || read.path.endsWith('/stderr.log')));
  unlinkSync(join(env.nodeDir, env.path, 'stdout.ndjson'));
  const calls = env.reads.length;
  assert.deepEqual(await env.runner.recoverRunReport(env.run), report);
  assert.equal(env.reads.length, calls);
});

test('the node rejects an oversized source before reading it and the combined real content IO stays within 8 MiB', async t => {
  const env = setup(t, 'x'.repeat(5 * 1024 * 1024));
  writeFileSync(join(env.nodeDir, env.path, 'stderr.log'), 'e'.repeat(4 * 1024 * 1024));
  await assert.rejects(env.runner.recoverRunReport(env.run), /限额|上限|超/);
  assert.equal(env.total(), 4 * 1024 * 1024);
  assert.ok(env.total() <= 8 * 1024 * 1024);
  assert.equal(env.reads.find(read => read.path.endsWith('/stdout.ndjson'))?.bytes, 0);
  assert.equal(env.f.ledger.runReport(env.run.id), undefined);
});

test('missing, unfinished and mismatching raw results are not promoted from diagnostic text', async t => {
  for (const output of [null, final('unfinished', false), final('wrong', true, { ...receipt, summary: 'other' })]) {
    const env = setup(t, output);
    await assert.rejects(env.runner.recoverRunReport(env.run), /恢复|回执/);
    assert.equal(env.f.ledger.runReport(env.run.id), undefined);
  }
});

test('owner gets a formal final reply after artifact/diagnostic expiry without a node, with only metadata in the task page', async t => {
  const app = await consoleApp(t);
  const { task, run } = app.f.runningRun();
  const body = 'PRIVATE_SYNTHETIC_FINAL_BODY';
  app.f.ledger.settleRun(run.id, 0, receipt, { finalReply: body });
  app.f.force('UPDATE run SET releases_dropped_at=? WHERE id=?', '2020-01-01T00:00:00Z', run.id);
  const page = await (await app.get(`/api/tasks/${task.id}`)).json() as { runs: { report_files: { kind?: string; ref: string }[] }[] };
  assert.equal(JSON.stringify(page).includes(body), false);
  assert.equal(page.runs[0]!.report_files[0]!.kind, 'final_message');
  const read = await app.get(`/api/runs/${run.id}/report?ref=${encodeURIComponent('最后一条消息')}`);
  assert.equal(read.status, 200);
  assert.equal((await read.json() as { text: string }).text, body);
  assert.equal((await app.get(`/api/runs/${run.id}/report?ref=unlisted.md`)).status, 400);
});


