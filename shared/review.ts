const VERDICT_IDS = ['pass', 'reject', 'cannot'] as const;
type VerdictId = (typeof VERDICT_IDS)[number];
export const VERDICT_LABELS: Readonly<Record<VerdictId, string>> = localeMap({
  pass: 'sh.review.verdict.pass',
  reject: 'sh.review.verdict.reject',
  cannot: 'sh.review.verdict.cannot',
});
export const isVerdictId = (value: unknown): value is VerdictId => (VERDICT_IDS as readonly unknown[]).includes(value);

// One requirement a rejected product breaks: which, what shows it, and what has to change.
export interface Violation {
  requirement: string;
  evidence: string;
  scope: string;
}

// A verdict as a receipt hands it over, once checked.
export interface Verdict {
  result: VerdictId;
  summary: string;
  // For a rejection: at least one.
  violations?: Violation[];
  // For "审不了": what was missing, or what in the environment stood in the way.
  missing?: string;
}

// One file the reviewed round left, as the host received and hashed it.
export interface BoundFile {
  name: string;
  sha256: string;
  bytes: number;
}

// What a review Task is bound to, generated by the service from what it holds — the
// reviewed Task, its round, the files that round left as the host registered them — and
// never from what the Router says. The reviewed Task's definition is copied as it was at
// that revision: it is what the reviewer is shown in place of anything its author wrote.
export interface ReviewOf {
  task_id: string;
  run_id: string;
  revision: number;
  title: string;
  goal: string;
  scope: string | null;
  acceptance: string | null;
  // The commit the reviewed round handed over, checked where it lives (shared/sources.ts
  // ReviewedCommit): for a repository, the branch it was pushed to and the commit the machine
  // read as that branch's head; for a folder, HEAD as the machine read it when the round
  // ended, and the folder it is in. Absent only when the reviewed Task has no code source at
  // all (or for a binding made before code sources): such a product has no commit a review
  // could be bound to.
  reviewed?: ReviewedCommit;
  // Where the reviewed Task's work started (§8 第 6 条): the HEAD the machine read when its
  // first round began — for a repository, the head of the branch it cloned. The review's
  // range is this commit to the reviewed one, and the brief says so; absent when no round
  // recorded one, and then the brief asks only for the reviewed commit.
  start?: string;
  // A final-message report is the product itself, not an author's explanation of code.
  report?: Pick<RunReportInfo, 'id' | 'sha256' | 'bytes' | 'complete'>;
  files: BoundFile[];
  // The executors of every round of the reviewed Task that really started and could write:
  // none of them may review it while another executor can (§4 ②; see sameExecutorReviewers).
  writers: string[];
  // The tier the reviewed round ran on, copied from its snapshot when the binding is made:
  // the review runs on that tier unless the Task's own override says otherwise (§11.5). A
  // binding made before that rule has none, and its review stays on the role's default.
  tier?: TierId;
  at: string;
}

// A review Task's verdict as the ledger keeps it: the round that handed it over, when, and
// whether at that moment it still spoke for the product it was bound to.
export interface VerdictRecord extends Verdict {
  run_id: string;
  at: string;
  current: boolean;
  // The executor that wrote the product and handed this verdict too, in a new session,
  // because no other could review it then (§4 ②). Absent: an independent review.
  same_executor?: string;
}

// Why a rejection moves the reviewed Task up a tier, in the words of the tier it goes to
// (roles-and-tiers.md §6, §10.3): the operate tier's product goes to execute, the execute
// tier's to decide. A Task already on the highest tier is the owner's to settle, below.
export const escalatedReason = (tier: TierId): string => t('sh.review.escalatedReason', { tier: tierLabel(tier) });
// The reason an execute-tier product used to be given, and the one the owner's own ledger
// already holds. Kept as the same sentence, so history reads as it was written.
export let ESCALATED_REASON: string = escalatedReason('decide');
// Why the Router cannot move an escalated Task back down: it was put on this tier by the
// service, and only the owner changes that (§6).
export const reviewTierLockText = (tier: string): string => t('sh.review.tierLock', { tier: tierLabel(tier) });
